# --------------------------------------------------------------------------- #
# What literal figures remain must be superseded runs that say so              #
# --------------------------------------------------------------------------- #

# A percentage with a sign reads as a result. Bare percentages are used for
# widths, opacities and prose ("100% of the time"), so signed literals are the
# ones worth policing.
_SIGNED_PCT = re.compile(r"(?:\+|&minus;|−|-)\d[\d,]*(?:\.\d+)?%")

# Each exemption needs a reason, and the reason has to be checkable on the page.
_ALLOWED = {
    "+0.0%": "hero chart placeholder, overwritten by initHero() on load",
    "+10%": "default position of the power-calculator effect-size slider",
    "+275.45%": "superseded v1 run, labelled and cited to commit d4c0ef9",
    "+19.57%": "superseded v1 benchmark, cited alongside it",
}


def test_every_literal_percentage_on_the_page_is_accounted_for(index: str):
    found = set(_SIGNED_PCT.findall(index))
    unexplained = found - set(_ALLOWED)
    assert not unexplained, (
        "literal result figures appeared in index.html: "
        f"{sorted(unexplained)}. Render them from a generated artifact, or add "
        "them to _ALLOWED with a reason if they are genuinely not live results."
    )


def test_the_superseded_figures_are_labelled_as_superseded(index: str):
    """Quoting an old run is fine. Quoting it as if current is not."""
    i = index.index("+275.45%")
