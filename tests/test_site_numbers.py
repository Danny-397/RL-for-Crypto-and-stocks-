"""The website must not carry hand-typed statistics.

Twice now a rebuild has moved a published number while the page kept showing the
old one: the domain-randomization table went on claiming a +36% held-out return
after the artifact said +47%, and the market explorer was still quoting a +275%
run and ``p = 0.97`` months after both had been superseded. Neither was caught by
a test, because nothing tested the *page* against the *experiments*.

That is the project's own thesis turned on itself. A number that has drifted away
from the run that produced it is not a rounding problem, it is a false claim, and
the site argues at length that those should be findable mechanically.

So these tests pin the mechanism rather than the digits: results reach the page
from generated artifacts, and the few literal figures that remain are superseded
runs that say so and cite the commit they came from.
"""

from __future__ import annotations

import json
import os
import re

import pytest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(REPO, "docs")


def _read(*parts: str) -> str:
    with open(os.path.join(DOCS, *parts), encoding="utf-8") as fh:
        return fh.read()


@pytest.fixture(scope="module")
def index() -> str:
    return _read("index.html")


@pytest.fixture(scope="module")
def app_js() -> str:
    return _read("app.js")


# --------------------------------------------------------------------------- #
# The shim and the artifact are the same numbers                               #
# --------------------------------------------------------------------------- #
def test_the_ablation_shim_matches_the_artifact_it_was_generated_from():
    """docs/ablation.js is written by the sweep; it must not be edited apart."""
    shim = _read("ablation.js")
    assert shim.startswith("/* Auto-generated by tools/ablation_multiseed.py")

    payload = json.loads(shim[shim.index("=") + 1: shim.rindex(";")])
    with open(os.path.join(DOCS, "assets", "ablation_multiseed.json"),
              encoding="utf-8") as fh:
        artifact = json.load(fh)
    assert payload["summary"] == artifact["summary"]
    assert payload["per_seed"] == artifact["per_seed"]


def test_the_shim_carries_the_per_seed_values_not_just_the_means():
    """A mean alone cannot be re-checked; the seeds behind it can."""
    shim = _read("ablation.js")
    payload = json.loads(shim[shim.index("=") + 1: shim.rindex(";")])
    for market in ("stock", "crypto"):
        for arm in ("single", "domain"):
            block = payload["summary"]["markets"][market][arm]
            assert len(block["oos_per_seed"]) == len(payload["summary"]["seeds"])
            assert len(block["in_per_seed"]) == len(payload["summary"]["seeds"])


