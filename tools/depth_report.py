"""Combine the depth study's CI outputs into the files the docs and site read.

The ``depth`` job in ``.github/workflows/rigor.yml`` (pre-registered in
``docs/preregistration/2026-11-14-depth.md``) uploads, in ``results/depth/``:
``sig30-<market>.js`` (30-seed significance), ``sweep-<market>.json``
(hyper-parameter sweep) and ``basket_walk_forward.json`` (the fold summary).
This writes ``docs/assets/depth.json`` (the first and last, with the Holm
adjustment of the registered family) and ``docs/assets/hyperparameter_sweep.json``
(both markets' sweep in the format the site panel and RESULTS.md §5b read), and
``docs/depth.js``, the few figures the site quotes.

    python tools/depth_report.py --in results/depth --run 43620358297
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from rl_trader.evaluation.rigor import holm  # noqa: E402


def _js(path: str) -> dict:
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    return json.loads(text[text.index("=") + 1: text.rindex(";")])


def combine(src: str, run: str) -> tuple:
    seeds = {}
    for market in ("stock", "crypto"):
        seeds.update(_js(os.path.join(src, f"sig30-{market}.js")))
    with open(os.path.join(src, "basket_walk_forward.json"), encoding="utf-8") as fh:
        wf = json.load(fh)
    family = {
        "P1.1 stocks, 30 seeds": seeds["stock"]["p"],
        "P1.2 crypto, 30 seeds": seeds["crypto"]["p"],
        "P2.1 stocks, walk-forward": wf["stock"]["pooled"]["p"],
        "P2.2 crypto, walk-forward": wf["crypto"]["pooled"]["p"],
    }
    depth = {
        "generated": time.strftime("%Y-%m-%d"),
        "workflow_run": run,
        "preregistration": "docs/preregistration/2026-11-14-depth.md",
        "seeds": seeds,
        "walk_forward": wf,
        "holm": holm(family),
    }

    sweep = None
    for market in ("stock", "crypto"):
        with open(os.path.join(src, f"sweep-{market}.json"), encoding="utf-8") as fh:
            part = json.load(fh)
        if sweep is None:
            sweep = {k: v for k, v in part.items() if k != "markets"}
            sweep["markets"] = {}
            sweep["workflow_run"] = run
        sweep["markets"].update(part["markets"])
    return depth, sweep


def site_summary(depth: dict) -> dict:
    """The handful of figures the site's notes quote, so they move with the data."""
    out = {"workflow_run": depth["workflow_run"], "seeds": {}, "walk_forward": {}, "behaviour": {}}
    for m in ("stock", "crypto"):
        r, w = depth["seeds"][m], depth["walk_forward"][m]
        out["seeds"][m] = {"n": r["seeds"], "mean": r["mean"], "bh": r["bh"], "p": r["p"],
                           "tickers": len(r["tickers"]),
                           "tickers_behind": r["robust"]["tickers_behind"]}
        out["walk_forward"][m] = {"folds": len(w["folds"]),
                                  "folds_behind": w["pooled"]["folds_behind"],
                                  "diff": w["pooled"]["diff"], "p": w["pooled"]["p"]}
        out["behaviour"][m] = r["risk"]["behaviour"]
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--in", dest="src", default=os.path.join("results", "depth"))
    ap.add_argument("--run", required=True, help="the workflow run id, for provenance")
    ap.add_argument("--assets", default=os.path.join("docs", "assets"))
    args = ap.parse_args()
    depth, sweep = combine(args.src, args.run)
    for name, data in (("depth.json", depth), ("hyperparameter_sweep.json", sweep)):
        path = os.path.join(args.assets, name)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(data, fh, indent=1, ensure_ascii=False)
            fh.write("\n")
        print(f"wrote {path}")
    site = os.path.join(os.path.dirname(args.assets), "depth.js")
    with open(site, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* Auto-generated by tools/depth_report.py from docs/assets/depth.json. */\n")
        fh.write("window.RL_DEPTH = " + json.dumps(site_summary(depth), indent=0) + ";\n")
    print(f"wrote {site}")


if __name__ == "__main__":
    main()
